// Embeds everything in web/ into worker/assets.mjs, which wrangler bundles.
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const TYPES = {'.css': 'text/css; charset=utf-8', '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.webmanifest': 'application/manifest+json', '.png': 'image/png', '.webp': 'image/webp'};
const assets = {};
// The design system's stylesheet is served from /design/ (its preview page is not), and illustrations from /img/.
const files = [...readdirSync('web').sort(), 'design/tokens.css', ...readdirSync('web/img').sort().map(name => 'img/' + name)];
for (const name of files) {
 const type = TYPES[name.slice(name.lastIndexOf('.'))];
 if (!type) continue;
 assets[name === 'index.html' ? '/' : '/' + name] = [type, readFileSync('web/' + name, type.startsWith('image/') ? 'base64' : 'utf8')];
}
// A content hash lets open pages notice a newer deploy (see web/sync.js).
const version = createHash('sha256').update(JSON.stringify(assets)).digest('hex').slice(0, 12);
assets['/'][1] = assets['/'][1].replace('__APP_VERSION__', version);
writeFileSync('worker/assets.mjs', '// Generated by scripts/build.mjs. Do not edit.\nexport const version = ' + JSON.stringify(version) + ';\nexport default ' + JSON.stringify(assets) + ';\n');
console.log('Embedded', Object.keys(assets).length, 'assets, version', version);
